// The REST client's types, in the shape openapi-typescript emits (`paths` →
// method → `parameters` / `requestBody` / `responses` → `content`), written
// with json-schema-to-typescript, which the MCP generator already uses.
// openapi-typescript itself needs TypeScript 5's compiler API, which the
// Desk's TypeScript 7 does not ship. `gen-api.ts` runs it.

import { compile, type JSONSchema } from "json-schema-to-typescript";
import type { Dokument } from "../src/data/api/dokument.ts";
import { BRANDS, brand, type Json } from "./marken.ts";

const METHODEN = ["get", "put", "post", "delete", "patch"] as const;

const pascal = (s: string) => s.replace(/(^|[-_.])(\w)/g, (_m, _sep, c: string) => c.toUpperCase());

/** `#/components/schemas/marktd.X` → `#/$defs/marktd.X`, the root's own definitions. */
function aufDefs(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(aufDefs);
  if (node === null || typeof node !== "object") return node;
  return Object.fromEntries(
    Object.entries(node as Json).map(([k, v]) => [
      k,
      k === "$ref" && typeof v === "string"
        ? v.replace("#/components/schemas/", "#/$defs/")
        : aufDefs(v),
    ]),
  );
}

const objekt = (properties: Json, required: string[]): Json => ({
  type: "object",
  properties,
  required,
  additionalProperties: false,
});

interface Parameter {
  name: string;
  in: string;
  required?: boolean;
  schema?: Json;
}

/** One operation in openapi-fetch's shape. */
function operation(op: Json): Json {
  const params = (op.parameters ?? []) as Parameter[];
  const gruppen: Json = {};
  const pflicht: string[] = [];
  for (const ort of ["path", "query", "header"]) {
    const hier = params.filter((p) => p.in === ort);
    if (hier.length === 0) continue;
    const req = hier.filter((p) => p.required || ort === "path").map((p) => p.name);
    gruppen[ort] = objekt(Object.fromEntries(hier.map((p) => [p.name, p.schema ?? {}])), req);
    if (req.length) pflicht.push(ort);
  }
  const inhalt = (c: unknown): Json | null => {
    const json = (c as Json | undefined)?.["application/json"] as Json | undefined;
    return json?.schema
      ? objekt({ "application/json": json.schema as Json }, ["application/json"])
      : null;
  };
  const body = op.requestBody as Json | undefined;
  const bodyInhalt = body ? inhalt(body.content) : null;
  const antworten: Json = {};
  for (const [code, r] of Object.entries((op.responses ?? {}) as Json)) {
    const c = inhalt((r as Json).content);
    antworten[code] = {
      type: "object",
      properties: {
        headers: { type: "object", additionalProperties: true },
        ...(c ? { content: c } : {}),
      },
      required: ["headers", ...(c ? ["content"] : [])],
      additionalProperties: false,
    };
  }
  return objekt(
    {
      parameters: objekt(gruppen, pflicht),
      ...(bodyInhalt ? { requestBody: objekt({ content: bodyInhalt }, ["content"]) } : {}),
      responses: objekt(antworten, Object.keys(antworten)),
    },
    ["parameters", ...(bodyInhalt && body?.required ? ["requestBody"] : []), "responses"],
  );
}

/** The merged document as one JSON schema whose type is `{ paths; components }`. */
export async function typen(d: Dokument): Promise<string> {
  const defs: Json = {};
  for (const [name, schema] of Object.entries(d.components?.schemas ?? {}))
    defs[name] = { ...(aufDefs(schema) as Json), title: pascal(name) };
  const paths: Json = {};
  for (const [pfad, ops] of Object.entries(d.paths ?? {})) {
    const methoden: Json = {};
    for (const m of METHODEN) if (ops[m]) methoden[m] = operation(aufDefs(ops[m]) as Json);
    paths[pfad] = objekt(methoden, Object.keys(methoden));
  }
  const root = brand({
    title: "Api",
    ...objekt(
      {
        paths: objekt(paths, Object.keys(paths)),
        components: objekt(
          {
            schemas: objekt(
              Object.fromEntries(Object.keys(defs).map((n) => [n, { $ref: `#/$defs/${n}` }])),
              Object.keys(defs),
            ),
          },
          ["schemas"],
        ),
      },
      ["paths", "components"],
    ),
    $defs: defs,
  }) as JSONSchema;
  const quelle = await compile(root, "Api", {
    bannerComment: "",
    additionalProperties: false,
    unknownAny: true,
    strictIndexSignatures: true,
  });
  // openapi-fetch matches a status as a number (`200`), as openapi-typescript
  // writes it; json-schema-to-typescript quotes every property name.
  const body = quelle.replace(/^(\s+)"(\d{3})": \{/gm, "$1$2: {");
  const brands = Object.values(BRANDS).filter((b) => body.includes(b));
  return [
    "// Generated by `npm run gen` from services/*/openapi.json — do not edit.",
    brands.length ? `import type { ${brands.join(", ")} } from "../../format/brands";` : "",
    "",
    body.trimEnd(),
    "",
    "/** What `openapi-fetch` reads: every path the gateway forwards, by method. */",
    'export type paths = Api["paths"];',
    'export type components = Api["components"];',
    "",
  ]
    .filter((line, i) => !(i === 1 && line === ""))
    .join("\n");
}
