// Generates the Desk's REST client types from the services' committed OpenAPI
// documents (`services/<service>/openapi.json`), merged as the gateway routes
// them:
//
//   npm run gen              writes openapi.json, src/data/api/schema.ts and stand.ts
//   npm run gen -- --check   exit 1 when a file differs from what it would write
//
// `openapi-fetch` reads `paths` from schema.ts, so a path or method no
// document describes does not type-check. `stand.ts` holds each document's
// `info.version` and fingerprint, which the drift banner compares with what
// the service serves.
//
// The types' shape is openapi-typescript's (`api-typen.ts` says why it is not
// openapi-typescript itself).

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { type Dokument, fehlendeSchemas, zusammenfuehren } from "../src/data/api/dokument.ts";
import { typen } from "./api-typen.ts";

const desk = resolve(import.meta.dirname, "..");
const repo = resolve(desk, "..");
const check = process.argv.includes("--check");

const dokumente: Record<string, Dokument> = {};
for (const service of readdirSync(resolve(repo, "services")).sort()) {
  const datei = resolve(repo, "services", service, "openapi.json");
  if (existsSync(datei)) dokumente[service] = JSON.parse(readFileSync(datei, "utf8")) as Dokument;
}
// A document that points at a schema it does not define cannot be typed; say
// which, instead of the resolver's stack trace.
let kaputt = 0;
for (const [service, d] of Object.entries(dokumente)) {
  const fehlt = fehlendeSchemas(d);
  if (fehlt.length) {
    console.error(
      `gen-api: services/${service}/openapi.json refers to schemas it does not define: ${fehlt.join(", ")}`,
    );
    kaputt++;
  }
}
if (kaputt) process.exit(1);

const { dokument, staende } = zusammenfuehren(dokumente);

const dateien: Record<string, string> = {
  "openapi.json": `${JSON.stringify(dokument, null, 2)}\n`,
  "src/data/api/schema.ts": await typen(dokument),
  "src/data/api/stand.ts": [
    "// Generated by `npm run gen` from services/*/openapi.json — do not edit.",
    'import type { Stand } from "./dokument";',
    "",
    "/** Each document the Desk was generated against: its `info.version` and fingerprint. */",
    `export const STAND: Record<string, Stand> = ${JSON.stringify(staende, null, 2)};`,
    "",
  ].join("\n"),
};

let stale = 0;
for (const [pfad, text] of Object.entries(dateien)) {
  const ziel = resolve(desk, pfad);
  if (check) {
    if (!existsSync(ziel) || readFileSync(ziel, "utf8") !== text) {
      console.error(`gen-api --check: ${pfad} is stale; run \`npm run gen\``);
      stale++;
    }
  } else writeFileSync(ziel, text);
}
process.exit(stale ? 1 : 0);
