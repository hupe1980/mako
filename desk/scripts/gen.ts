// Generates src/data/gen/<service>.ts from services/<service>/mcp.snapshot.json.
//
//   npm run gen              write the files
//   npm run gen -- --check   exit 1 when a file differs from what it would write
//
// Each service becomes one interface `<Service>Tools` mapping every *typed* tool
// (one whose snapshot has an outputSchema) to `{ input; output }`. The Rust type
// names survive: schemars titles a schema after its type, so `ProcessView` is
// `ProcessView` here too. Formats map to branded strings, so a value can only be
// shown through src/format: date-time → Instant, date → BusinessDate,
// decimal → Decimal.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const desk = resolve(import.meta.dirname, "..");
const repo = resolve(desk, "..");
const out = resolve(desk, "src/data/gen");
const check = process.argv.includes("--check");

const BRANDS: Record<string, string> = {
  "date-time": "Instant",
  date: "BusinessDate",
  decimal: "Decimal",
};

interface SnapshotTool {
  name: string;
  inputSchema: JSONSchema;
  outputSchema: JSONSchema | null;
}

type Json = { [key: string]: unknown };

/** Replace a branded `format` with the brand's type, keeping `| null`. */
function brand(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(brand);
  if (node === null || typeof node !== "object") return node;
  const obj = node as Json;
  const tsType = typeof obj.format === "string" ? BRANDS[obj.format] : undefined;
  if (tsType) {
    const nullable = Array.isArray(obj.type) && obj.type.includes("null");
    const { format: _f, type: _t, ...rest } = obj;
    return { ...rest, tsType: nullable ? `${tsType} | null` : tsType };
  }
  return Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, brand(v)]));
}

/** Move a schema's `$defs` into `defs`, refusing two different shapes under one name. */
function hoist(schema: JSONSchema, defs: Json, where: string): JSONSchema {
  const { $defs, ...rest } = schema as Json;
  for (const [name, def] of Object.entries(($defs ?? {}) as Json)) {
    const prior = defs[name];
    if (prior !== undefined && JSON.stringify(prior) !== JSON.stringify(def)) {
      throw new Error(`${where}: $defs/${name} has two different shapes`);
    }
    defs[name] = def;
  }
  return rest as JSONSchema;
}

function pascal(s: string): string {
  return s.replace(/(^|[-_])(\w)/g, (_m, _sep, c: string) => c.toUpperCase());
}

async function render(service: string, tools: SnapshotTool[]): Promise<string> {
  const typed = tools.filter((t) => t.outputSchema !== null);
  const untyped = tools.filter((t) => t.outputSchema === null).map((t) => t.name);
  const defs: Json = {};
  const properties: Json = {};
  for (const t of typed) {
    const where = `${service}.${t.name}`;
    properties[t.name] = {
      type: "object",
      properties: {
        input: hoist(t.inputSchema, defs, where),
        output: hoist(t.outputSchema as JSONSchema, defs, where),
      },
      required: ["input", "output"],
      additionalProperties: false,
    };
  }
  const root = brand({
    title: `${pascal(service)}Tools`,
    type: "object",
    properties,
    required: typed.map((t) => t.name),
    additionalProperties: false,
    $defs: defs,
  }) as JSONSchema;

  const body = typed.length
    ? await compile(root, `${pascal(service)}Tools`, {
        bannerComment: "",
        additionalProperties: false,
        unknownAny: true,
        strictIndexSignatures: true,
      })
    : `export interface ${pascal(service)}Tools {}\n`;
  const brands = Object.values(BRANDS).filter((b) => body.includes(b));
  return [
    `// Generated by \`npm run gen\` from services/${service}/mcp.snapshot.json — do not edit.`,
    brands.length ? `import type { ${brands.join(", ")} } from "../../format/brands";` : "",
    "",
    body.trimEnd(),
    "",
    `/** Tools ${service} serves without an output schema: no view may read them. */`,
    `export const ${service}Untyped = ${JSON.stringify(untyped)} as const;`,
    "",
  ]
    .filter((line, i) => !(i === 1 && line === ""))
    .join("\n");
}

const services = readdirSync(resolve(repo, "services")).filter((s) =>
  existsSync(resolve(repo, "services", s, "mcp.snapshot.json")),
);
let drift = 0;
for (const service of services) {
  const snapshot = resolve(repo, "services", service, "mcp.snapshot.json");
  const tools = JSON.parse(readFileSync(snapshot, "utf8")) as SnapshotTool[];
  const file = resolve(out, `${service}.ts`);
  const text = await render(service, tools);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
      console.error(`gen --check: src/data/gen/${service}.ts is stale; run \`npm run gen\``);
      drift++;
    }
  } else {
    writeFileSync(file, text);
  }
}
for (const file of readdirSync(out)) {
  if (!services.includes(file.replace(/\.ts$/, ""))) {
    console.error(`gen: src/data/gen/${file} has no snapshot; delete it`);
    drift++;
  }
}
process.exit(drift ? 1 : 0);
