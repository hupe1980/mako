//! `cargo xtask api-catalog [--check]`: publish every committed
//! `services/<svc>/openapi.json` as `site/static/api/<svc>.json` and generate
//! `site/content/docs/reference/api.md`, the one page linking each.
//!
//! The committed document is the source — each service's test holds it to the
//! routes it mounts (`mako_service::openapi::assert_committed`) — so the site
//! carries a byte copy and a page generated from it, and `--check` refuses a
//! copy, a page or a stale file that differs from what the tree commits.

use std::collections::BTreeMap;
use std::path::Path;

const PAGE: &str = "site/content/docs/reference/api.md";
const STATIC: &str = "site/static/api";
const BASE: &str = "https://hupe1980.github.io/mako/api";

/// One service's committed document: its name and its text.
type Documents = BTreeMap<String, String>;

fn documents(root: &Path) -> Result<Documents, String> {
    let mut out = Documents::new();
    let dir = root.join("services");
    let entries = std::fs::read_dir(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries.flatten() {
        let file = entry.path().join("openapi.json");
        if file.is_file() {
            let text =
                std::fs::read_to_string(&file).map_err(|e| format!("{}: {e}", file.display()))?;
            out.insert(entry.file_name().to_string_lossy().into_owned(), text);
        }
    }
    Ok(out)
}

fn render(docs: &Documents) -> Result<String, String> {
    let mut rows = String::new();
    for (svc, text) in docs {
        let doc: serde_json::Value =
            serde_json::from_str(text).map_err(|e| format!("services/{svc}/openapi.json: {e}"))?;
        let operations: usize = doc["paths"].as_object().map_or(0, |paths| {
            paths
                .values()
                .filter_map(serde_json::Value::as_object)
                .map(|ops| {
                    ops.keys()
                        .filter(|m| ["get", "put", "post", "delete", "patch"].contains(&m.as_str()))
                        .count()
                })
                .sum()
        });
        let title = doc["info"]["title"]
            .as_str()
            .unwrap_or(svc)
            .replace('|', "\\|");
        rows.push_str(&format!(
            "| `{svc}` | {title} | {operations} | [`{svc}.json`]({BASE}/{svc}.json) | [guide](@/docs/services/{svc}.md) |\n"
        ));
    }
    Ok(format!(
        r#"+++
title = "HTTP APIs"
description = "Published OpenAPI 3.1 documents and operator guides for mako services."
weight = 21
+++
<!-- Generated by `cargo xtask api-catalog` from services/*/openapi.json. Do
     not edit: `cargo xtask api-catalog --check` refuses a page that differs. -->

This catalog contains {count} committed OpenAPI documents. Each listed service
serves its document at `GET /api/v1/openapi.json`. Download the document to
generate a client or open it in an OpenAPI viewer. Consult the operation's
response schemas for its success and refusal bodies.

| Service | Title | Operations | Document | Operator guide |
|---|---|---|---|---|
{rows}"#,
        count = docs.len(),
    ))
}

/// Write (or with `check`, compare) the copies and the page. `false` on a
/// difference or an error, each named on stderr.
pub fn run(root: &Path, check: bool) -> bool {
    let docs = match documents(root) {
        Ok(d) if d.len() >= 4 => d,
        Ok(d) => {
            eprintln!(
                "api-catalog: found {} committed documents; the scan broke, not the tree",
                d.len()
            );
            return false;
        }
        Err(e) => {
            eprintln!("api-catalog: {e}");
            return false;
        }
    };
    let page = match render(&docs) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("api-catalog: {e}");
            return false;
        }
    };
    let problems = if check {
        compare(root, &docs, &page)
    } else {
        write(root, &docs, &page)
    };
    for p in &problems {
        eprintln!("api-catalog: {p}");
    }
    problems.is_empty()
}

fn compare(root: &Path, docs: &Documents, page: &str) -> Vec<String> {
    let mut problems = Vec::new();
    if std::fs::read_to_string(root.join(PAGE)).ok().as_deref() != Some(page) {
        problems.push(format!("{PAGE} is stale — run `cargo xtask api-catalog`"));
    }
    for (svc, text) in docs {
        let copy = root.join(STATIC).join(format!("{svc}.json"));
        if std::fs::read_to_string(&copy).ok().as_deref() != Some(text.as_str()) {
            problems.push(format!(
                "{STATIC}/{svc}.json differs from services/{svc}/openapi.json — run `cargo xtask api-catalog`"
            ));
        }
    }
    for entry in std::fs::read_dir(root.join(STATIC))
        .into_iter()
        .flatten()
        .flatten()
    {
        let name = entry.file_name().to_string_lossy().into_owned();
        let svc = name.strip_suffix(".json").unwrap_or(&name);
        if !docs.contains_key(svc) {
            problems.push(format!(
                "{STATIC}/{name} has no services/{svc}/openapi.json — run `cargo xtask api-catalog`"
            ));
        }
    }
    problems
}

fn write(root: &Path, docs: &Documents, page: &str) -> Vec<String> {
    let mut problems = Vec::new();
    let dir = root.join(STATIC);
    if let Err(e) = std::fs::create_dir_all(&dir) {
        return vec![format!("{STATIC}: {e}")];
    }
    for entry in std::fs::read_dir(&dir).into_iter().flatten().flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        if !docs.contains_key(name.strip_suffix(".json").unwrap_or(&name))
            && let Err(e) = std::fs::remove_file(entry.path())
        {
            problems.push(format!("{STATIC}/{name}: {e}"));
        }
    }
    for (svc, text) in docs {
        if let Err(e) = std::fs::write(dir.join(format!("{svc}.json")), text) {
            problems.push(format!("{STATIC}/{svc}.json: {e}"));
        }
    }
    if let Err(e) = std::fs::write(root.join(PAGE), page) {
        problems.push(format!("{PAGE}: {e}"));
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Tmp(std::path::PathBuf);
    impl Tmp {
        fn path(&self) -> &Path {
            &self.0
        }
    }
    impl Drop for Tmp {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    fn tree(name: &str) -> (Tmp, Documents, String) {
        let tmp =
            Tmp(std::env::temp_dir()
                .join(format!("mako-api-catalog-{name}-{}", std::process::id())));
        let _ = std::fs::remove_dir_all(tmp.path());
        let root = tmp.path();
        for svc in ["a", "b", "c", "d"] {
            let dir = root.join("services").join(svc);
            std::fs::create_dir_all(&dir).expect("dir");
            std::fs::write(
                dir.join("openapi.json"),
                format!(r#"{{"info":{{"title":"{svc}d"}},"paths":{{"/x":{{"get":{{}}}}}}}}"#),
            )
            .expect("write");
        }
        std::fs::create_dir_all(root.join("site/content/docs/reference")).expect("dir");
        let docs = documents(root).expect("documents");
        let page = render(&docs).expect("page");
        (tmp, docs, page)
    }

    /// A page or a copy that differs from what the services commit fails the
    /// check; writing them makes it pass.
    #[test]
    fn a_stale_copy_or_page_fails() {
        let (tmp, docs, page) = tree("stale");
        assert!(!compare(tmp.path(), &docs, &page).is_empty());
        assert!(write(tmp.path(), &docs, &page).is_empty());
        assert!(compare(tmp.path(), &docs, &page).is_empty());
        std::fs::write(tmp.path().join(STATIC).join("a.json"), "{}").expect("write");
        let problems = compare(tmp.path(), &docs, &page);
        assert!(problems[0].contains("a.json differs"), "{problems:?}");
    }

    /// A published copy whose service no longer commits a document fails.
    #[test]
    fn an_orphaned_copy_fails() {
        let (tmp, docs, page) = tree("orphan");
        assert!(write(tmp.path(), &docs, &page).is_empty());
        std::fs::write(tmp.path().join(STATIC).join("gone.json"), "{}").expect("write");
        let problems = compare(tmp.path(), &docs, &page);
        assert!(problems[0].contains("gone.json has no"), "{problems:?}");
    }

    /// The page names each service with its operation count and link.
    #[test]
    fn the_page_lists_each_document() {
        let (_tmp, _docs, page) = tree("page");
        assert!(page.contains("This catalog contains 4 committed OpenAPI documents."));
        assert!(page.contains(&format!("| `b` | bd | 1 | [`b.json`]({BASE}/b.json)")));
    }
}
